-- ============================================
-- PASO 5 - USUARIO Y PRIVILEGIOS DEL DW
-- Ejecutar conectado como DBA.
-- &DW_PASSWORD se solicita como variable de sustitucion.
-- ============================================

CREATE USER CINECOL_DW IDENTIFIED BY &DW_PASSWORD
    DEFAULT TABLESPACE USERS
    TEMPORARY TABLESPACE TEMP
    QUOTA UNLIMITED ON USERS;

GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE,
      CREATE VIEW TO CINECOL_DW;

GRANT SELECT ON CINECOL_R.ciudad TO CINECOL_DW;
GRANT SELECT ON CINECOL_R.sucursal TO CINECOL_DW;
GRANT SELECT ON CINECOL_R.sala TO CINECOL_DW;
GRANT SELECT ON CINECOL_R.asiento TO CINECOL_DW;
GRANT SELECT ON CINECOL_R.empleado TO CINECOL_DW;
GRANT SELECT ON CINECOL_R.cliente TO CINECOL_DW;
GRANT SELECT ON CINECOL_R.genero TO CINECOL_DW;
GRANT SELECT ON CINECOL_R.clasificacion TO CINECOL_DW;
GRANT SELECT ON CINECOL_R.pelicula TO CINECOL_DW;
GRANT SELECT ON CINECOL_R.funcion TO CINECOL_DW;
GRANT SELECT ON CINECOL_R.metodo_pago TO CINECOL_DW;
GRANT SELECT ON CINECOL_R.venta TO CINECOL_DW;
GRANT SELECT ON CINECOL_R.boleto TO CINECOL_DW;

SELECT username, account_status FROM dba_users WHERE username = 'CINECOL_DW';

